CREATE TABLE IF NOT EXISTS customer (
  custno TEXT PRIMARY KEY,
  custname TEXT NOT NULL,
  address TEXT NOT NULL,
  payterm TEXT NOT NULL,
  is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
  stamp TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS employee (
  empno TEXT PRIMARY KEY,
  firstname TEXT NOT NULL,
  lastname TEXT NOT NULL,
  gender TEXT,
  hiredate DATE,
  sepdate DATE,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS product (
  prodcode TEXT PRIMARY KEY,
  description TEXT NOT NULL,
  unit TEXT NOT NULL,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS pricehist (
  price_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prodcode TEXT NOT NULL REFERENCES product(prodcode),
  unitprice NUMERIC(12, 2) NOT NULL CHECK (unitprice >= 0),
  effdate DATE NOT NULL DEFAULT CURRENT_DATE,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS sales (
  transno TEXT PRIMARY KEY,
  salesdate DATE NOT NULL DEFAULT CURRENT_DATE,
  custno TEXT NOT NULL REFERENCES customer(custno),
  empno TEXT NOT NULL REFERENCES employee(empno),
  stamp TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS salesdetail (
  detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transno TEXT NOT NULL REFERENCES sales(transno) ON DELETE CASCADE,
  prodcode TEXT NOT NULL REFERENCES product(prodcode),
  quantity INTEGER NOT NULL CHECK (quantity > 0)
);

ALTER TABLE customer
  ADD COLUMN IF NOT EXISTS is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS is_deleted BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE pricehist
  ADD COLUMN IF NOT EXISTS price_id BIGINT GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE salesdetail
  ADD COLUMN IF NOT EXISTS detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY;

DROP VIEW IF EXISTS customer_active CASCADE;
DROP VIEW IF EXISTS employee_active CASCADE;
DROP VIEW IF EXISTS pricehist_active CASCADE;
DROP VIEW IF EXISTS salesdetail_active CASCADE;

CREATE OR REPLACE VIEW customer_active AS
SELECT custno, custname
FROM customer
WHERE is_blocked = FALSE
  AND is_deleted = FALSE;

CREATE OR REPLACE VIEW employee_active AS
SELECT empno, firstname, lastname, gender, hiredate, sepdate
FROM employee
WHERE sepdate IS NULL AND is_deleted = FALSE;

CREATE OR REPLACE VIEW pricehist_active AS
SELECT DISTINCT ON (prodcode) prodcode, unitprice, effdate
FROM pricehist
WHERE is_deleted = FALSE
  AND effdate <= CURRENT_DATE
ORDER BY prodcode, effdate DESC, price_id DESC;

CREATE OR REPLACE VIEW salesdetail_active AS
SELECT detail_id, transno, prodcode, quantity
FROM salesdetail
WHERE EXISTS (
  SELECT 1
  FROM sales
  WHERE sales.transno = salesdetail.transno
    AND sales.is_deleted = FALSE
);

CREATE OR REPLACE FUNCTION create_sale_transaction(
  p_transno TEXT,
  p_salesdate DATE,
  p_custno TEXT,
  p_empno TEXT,
  p_items JSONB
)
RETURNS sales
LANGUAGE plpgsql
AS $$
DECLARE
  item JSONB;
  created_sale sales;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM customer_active WHERE custno = p_custno) THEN
    RAISE EXCEPTION 'Selected customer is not active';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM employee_active WHERE empno = p_empno) THEN
    RAISE EXCEPTION 'Selected employee is not active';
  END IF;

  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'At least one sale item is required';
  END IF;

  FOR item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pricehist_active
      WHERE prodcode = item->>'prodcode'
    ) THEN
      RAISE EXCEPTION 'Product % is not active or has no price', item->>'prodcode';
    END IF;

    IF (item->>'quantity')::INTEGER <= 0
       OR (item->>'quantity')::INTEGER <> (item->>'quantity')::NUMERIC THEN
      RAISE EXCEPTION 'Sale quantity must be a positive whole number';
    END IF;
  END LOOP;

  INSERT INTO sales (transno, salesdate, custno, empno)
  VALUES (p_transno, p_salesdate, p_custno, p_empno)
  RETURNING * INTO created_sale;

  INSERT INTO salesdetail (transno, prodcode, quantity)
  SELECT p_transno, item->>'prodcode', (item->>'quantity')::INTEGER
  FROM jsonb_array_elements(p_items) AS item;

  RETURN created_sale;
END;
$$;
