CREATE TABLE IF NOT EXISTS audit_log (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id UUID NOT NULL,
  action TEXT NOT NULL,
  table_name TEXT NOT NULL,
  record_id TEXT NOT NULL,
  details JSONB NOT NULL DEFAULT '{}'::JSONB,
  action_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION audit_user(
  p_actor_user_id UUID,
  p_action TEXT,
  p_table_name TEXT,
  p_record_id TEXT,
  p_details JSONB DEFAULT '{}'::JSONB
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
  INSERT INTO audit_log (actor_user_id, action, table_name, record_id, details)
  VALUES (p_actor_user_id, p_action, p_table_name, p_record_id, COALESCE(p_details, '{}'::JSONB));
END;
$$;

CREATE OR REPLACE FUNCTION set_module_right(
  p_actor_user_id UUID,
  p_target_user_id UUID,
  p_module TEXT,
  p_action TEXT,
  p_granted BOOLEAN
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
  right_exists BOOLEAN;
  actor_role_id INTEGER;
BEGIN
  SELECT role_id INTO actor_role_id
  FROM app_user
  WHERE user_id = p_actor_user_id;

  IF actor_role_id IS NULL OR actor_role_id NOT IN (1, 2) THEN
    RAISE EXCEPTION 'Only administrators may modify module rights.';
  END IF;

  IF p_module NOT IN ('customer', 'product', 'human-resources', 'sales', 'reports')
     OR p_action NOT IN (
       'add-customer', 'delete-customer', 'edit-customer',
       'add-product', 'delete-product', 'edit-product', 'add-price', 'edit-price', 'delete-price',
       'add-job', 'delete-job', 'edit-job', 'add-department', 'delete-department', 'edit-department',
       'add-employee', 'delete-employee', 'edit-employee', 'view-job-history', 'add-job-history', 'delete-job-history', 'edit-job-history',
       'add-sale', 'edit-sale', 'delete-sale', 'add-sale-detail', 'view-sale-details', 'edit-sale-detail', 'delete-sale-detail',
       'top-customers', 'top-products', 'all-employees', 'active-employees', 'employee-job-history', 'top-sales', 'product-master-list'
     ) THEN
    RAISE EXCEPTION 'Invalid module or action.';
  END IF;

  SELECT EXISTS (
    SELECT 1
    FROM user_rights
    WHERE user_id = p_target_user_id::TEXT
      AND module_name = p_module
      AND action_key = p_action
      AND is_allowed = TRUE
      AND is_deleted = FALSE
  ) INTO right_exists;

  IF right_exists = p_granted THEN
    RETURN;
  END IF;

  IF p_granted THEN
    UPDATE user_rights
    SET is_allowed = TRUE, is_deleted = FALSE, stamp = NOW()::TEXT
    WHERE user_id = p_target_user_id::TEXT
      AND module_name = p_module
      AND action_key = p_action;

    IF NOT FOUND THEN
      INSERT INTO user_rights (user_id, module_name, action_key, is_allowed, is_deleted, stamp)
      VALUES (p_target_user_id::TEXT, p_module, p_action, TRUE, FALSE, NOW()::TEXT);
    END IF;
  ELSE
    UPDATE user_rights
    SET is_allowed = FALSE, is_deleted = TRUE, stamp = NOW()::TEXT
    WHERE user_id = p_target_user_id::TEXT
      AND module_name = p_module
      AND action_key = p_action;
  END IF;

  PERFORM audit_user(
    p_actor_user_id,
    CASE WHEN p_granted THEN 'GRANT_RIGHT' ELSE 'REVOKE_RIGHT' END,
    'user_rights',
    p_target_user_id::TEXT,
    jsonb_build_object('module', p_module, 'action', p_action, 'granted', p_granted)
  );
END;
$$;
